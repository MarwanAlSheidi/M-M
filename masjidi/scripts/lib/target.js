/**
 * أيُّ خادمٍ يعمل عليه هذا الأمر؟
 *
 * `docs/DEPLOY.md` يوصي بتطبيقٍ تجريبي قبل الحقيقي — **فوجودُ تطبيقين هو
 * الحالة المتوقَّعة لا الشاذّة**، والفرق بينهما سطرٌ في `.env` يُبدَّل باليد.
 *
 * وقِيس: من أربع أدواتٍ تلمس خادماً، **ثلاثٌ لا تقول أين تعمل** —
 * `seed_mosques` و`apply_schema` و`promote_admin`. والوحيدة التي تقول
 * (`preflight`) هي **القراءة المحضة**، أي أقلُّها ضرراً لو أخطأت الوجهة.
 *
 * وأثرُ الخطأ ليس واحداً: ترقيةُ مشرفٍ في التطبيق الخطأ تُصحَّح بأمرٍ آخر،
 * **واستيرادُ 18,214 مسجداً في التطبيق الخطأ يُنفق باقتَه ولا يُستردّ**.
 *
 * فيُطبع المضيفُ ومقدّمةُ معرّف التطبيق قبل كل عمل. **ولا يُطبع المفتاح
 * الرئيس ولا معرّف التطبيق كاملاً**: المقصود أن يُميِّز المُشغّل بين تطبيقيه،
 * لا أن يُنسخ سرٌّ إلى سجلٍّ أو لقطة شاشة.
 */

/** مضيفُ الخادم كما يُقرأ، أو العنوان كما هو إن تعذّر تحليله. */
function hostOf(serverURL) {
  try {
    return new URL(serverURL).host;
  } catch (_) {
    return String(serverURL || '(بلا عنوان)');
  }
}

/**
 * يطبع وجهة الأمر قبل تنفيذه.
 *
 * @param {string} action ما سيجري — بصيغة الفعل، ليُقرأ السطر جملةً
 */
function announceTarget(action, env = process.env) {
  const host = hostOf(env.PARSE_SERVER_URL);
  const appId = String(env.PARSE_APP_ID || '');
  // ستّةٌ تكفي للتمييز بين تطبيقين ولا تكفي لاستعمالها
  const shown = appId ? `${appId.slice(0, 6)}…` : '(بلا معرّف)';
  console.log(`→ ${action} على ${host} (التطبيق ${shown})`);
}

module.exports = { announceTarget, hostOf };
