/**
 * عدّاد غير المقروء — مرّةً لا مع كل ضغطة.
 *
 * **قِيس في متصفّح حقيقي:** كل ضغطة تبويب كانت تُطلق `getMyNotifications`
 * لتحديث الشارة. وعلى تبويب «التنبيهات» تُجلب البيانات نفسها مرّتين: مرّةً
 * للشاشة ومرّةً للرقم الصغير فوقها.
 *
 * والطلبات هي **القيد الملزم** في باقة Back4app لا المساحة (25 ألفاً شهرياً).
 * فمئةُ مستخدمٍ يضغط كلٌّ منهم عشرين تبويباً يومياً = ستون ألف طلب في الشهر —
 * **ضعفا الباقة كلِّها، لرقمٍ على زرّ.**
 *
 * فالعدد يُحفظ هنا مع لحظة جلبه: يُعاد استعماله ما دام طرياً، ويُنشر عند كل
 * قراءةٍ صادقة (شاشة التنبيهات تعرف العدد أصلاً، والتعليم مقروءاً يُصفّره)
 * فتتحدّث الشارة **بلا طلبٍ إضافي**.
 *
 * وملفٌّ بلا استيرادات قصداً — يختبره `tests/unread.test.js` باستيرادٍ ديناميكي.
 */

/**
 * ما دون هذه المدّة يُعدّ طرياً.
 *
 * الشارة ليست مصدر الخبر — الخبر في شاشة «التنبيهات» وهي تُجلب دائماً. فتأخّرُ
 * الرقم دقيقةً لا يُفوّت على أحد شيئاً، وتحديثُه مع كل ضغطة يُنفق الباقة على
 * زينة. وينتفي التأخّر أصلاً متى قرأ المستخدم تنبيهاته: القراءة تنشر العدد.
 */
const FRESH_MS = 60 * 1000;

let value = null;
let fetchedAt = 0;
const listeners = new Set();

/** العدد المحفوظ إن كان طرياً، وإلا `null` — فيُجلب. */
export function cachedUnread(now = Date.now()) {
  if (value == null || !fetchedAt) return null;
  return now - fetchedAt < FRESH_MS ? value : null;
}

/** يُعلن عدداً معلوماً — من جلبٍ صريح أو من شاشةٍ عرفته ضمناً. */
export function publishUnread(count, now = Date.now()) {
  value = Number(count) || 0;
  fetchedAt = now;
  for (const listener of [...listeners]) listener(value);
}

/** يشترك في التغيّر، ويُعيد دالة فكّ الاشتراك. */
export function onUnread(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/**
 * يُنسي المحفوظ — عند الخروج وعند زوال الجلسة.
 *
 * بدونه يرى **المستخدم التالي على الجهاز نفسه** شارةَ من قبله: رقمٌ ليس له،
 * يقوده إلى وارده الفارغ فيحسبه عطباً. والمشترك لا يُمسّ: الشاشة قائمة.
 */
export function resetUnread() {
  value = null;
  fetchedAt = 0;
  for (const listener of [...listeners]) listener(0);
}
