/**
 * ما يُقال للمستخدم حين يقع خطأ.
 *
 * رسائلُنا عربيةٌ تُصاغ في `cloud/lib/errors.js`. **ورسائل Parse نفسه
 * إنجليزية** — وتصل المستخدم في مسارين لا يمرّان بدوال السحابة: الدخول
 * والتسجيل، **ورفع الصور**.
 *
 * قِيس على خادمٍ حقيقي: رفعٌ إلى خادمٍ لم يُفعَّل فيه الرفع يردّ
 * `130 · File upload by public is disabled.` — **فتُعرض بالإنجليزية لمتطوّعٍ
 * واقفٍ في مسجدٍ يُبلغ عن عمله**. وتفعيلُ الرفع خطوةُ نشرٍ يدوية في
 * `docs/DEPLOY.md`، أي أنها تُنسى — فيصير كلُّ إبلاغٍ بصورة طريقاً مسدوداً
 * برسالةٍ لا يقرؤها صاحبها.
 *
 * والقاعدة هنا: **لا تصل المستخدمَ العربيَّ رسالةٌ إنجليزية أبداً.** ما لا
 * ترجمة له يُقال بالعربية ومعه رمزُه — فالرمز يُعين الإدارة ولا يُربك القارئ.
 *
 * وملفٌّ بلا استيرادات قصداً: يختبره `tests/messages.test.js` باستيرادٍ
 * ديناميكي، ولو لمس `parse` لما عمل خارج المتصفّح.
 */

/** أكوادُ Parse التي تبلغ المستخدم فعلاً، ولكلٍّ ما يفعله بعدها. */
export const PARSE_MESSAGES = {
  100: 'تعذّر الوصول إلى الخادم — تحقّق من اتصالك.',
  101: 'اسم المستخدم أو كلمة المرور غير صحيحة.',
  119: 'لا صلاحية لك على هذا الإجراء.',
  124: 'استغرق الطلب وقتاً طويلاً — حاول مرة أخرى.',
  130: 'تعذّر رفع الصور — الخدمة غير مهيّأة على الخادم. أبلغ الإدارة، '
    + 'ويمكنك الإبلاغ بلا صور.',
  200: 'اسم المستخدم مطلوب.',
  201: 'كلمة المرور مطلوبة.',
  202: 'اسم المستخدم مسجَّل مسبقاً — اختر غيره.',
  203: 'البريد مسجَّل مسبقاً.',
  209: 'انتهت جلستك — سجّل الدخول من جديد.',
};

const hasArabic = (text) => /[؀-ۿ]/.test(text);

/**
 * الرسالة كما تُعرض.
 *
 * الفصلُ بين رسالتنا ورسالة Parse **بالحرف لا بالكود**: كودٌ واحد يأتي من
 * الطرفين (119 من الخادم ومن حارسنا)، فما فيه حرفٌ عربي فهو منّا.
 */
export const messageOf = (error) => {
  if (!error) return 'تعذّر إتمام العملية، حاول مرة أخرى.';
  if (error.message && hasArabic(error.message)) return error.message;

  if (PARSE_MESSAGES[error.code]) return PARSE_MESSAGES[error.code];

  // لا ترجمة له: يُقال بالعربية ومعه رمزُه. وكان يُعرض نصُّ Parse الإنجليزي.
  return error.code
    ? `تعذّر إتمام العملية (رمز ${error.code}). حاول مرة أخرى، وإن تكرّر فأبلغ الإدارة.`
    : 'تعذّر إتمام العملية، حاول مرة أخرى.';
};
